export const DICTS = { fr, en };
const I18n = createContext(null);

function initialLang() {
  const saved = localStorage.getItem('chaos.lang');
  if (saved === 'fr' || saved === 'en') return saved;
  return navigator.language?.startsWith('en') ? 'en' : 'fr';
}

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(initialLang);
  const setLang = (l) => {
    localStorage.setItem('chaos.lang', l);
    document.documentElement.lang = l;
    setLangState(l);
  };
  const t = (key) => DICTS[lang][key] ?? key;
  /** Picks the current language from a {fr, en} object (catalog texts). */
  const tr = (obj) => (typeof obj === 'string' ? obj : (obj?.[lang] ?? obj?.fr ?? ''));
  return <I18n.Provider value={{ lang, setLang, t, tr }}>{children}</I18n.Provider>;
}

export const useI18n = () => useContext(I18n);
